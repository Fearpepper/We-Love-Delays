// Run with: node tests/journey.test.js
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('assets/app.js','utf8');
const navigation=fs.readFileSync('assets/navigation.js','utf8');
const dashboard=fs.readFileSync('assets/dashboard.js','utf8');
const css=fs.readFileSync('assets/app.css','utf8');
const design=fs.readFileSync('assets/design.css','utf8');
const scripts=[app,navigation,dashboard];
assert(scripts.length>0,'JavaScript scripts exist');
for(const script of scripts)new vm.Script(script);
const start=app.indexOf('function chooseScheduledConnection('),end=app.indexOf('function appendTripTiming(',start);
assert(start>=0&&end>start,'connection calculator exists');
const ctx={Date,Number,Array};vm.createContext(ctx);
vm.runInContext(app.slice(start,end)+';this.choose=chooseScheduledConnection;',ctx);
const choose=ctx.choose,now=Date.now(),at=m=>new Date(now+m*60000).toISOString();
const walks=[{minutes:5},{minutes:5},{minutes:4}];
const schedules=[[{departure:at(20),arrival:at(35)}],[{departure:at(45),arrival:at(60)}]];
assert.equal(choose(schedules,walks,null).chain.length,2,'valid transfer');
assert.equal(choose(schedules,[{minutes:5},{minutes:12},{minutes:4}],null).length,0,'reject impossible transfer');
assert.equal(choose(schedules,walks,now+50*60000).length,0,'reject missed arrival deadline');
assert.equal(choose(schedules,[null,{minutes:5},{minutes:4}],null),null,'unknown pedestrian leg');
assert.equal(choose([[],schedules[1]],walks,null).length,0,'no scheduled departure');
const alternatives=[[{departure:at(20),arrival:at(35)}],[{departure:at(45),arrival:at(90)},{departure:at(55),arrival:at(70)}]];
assert.equal(choose(alternatives,walks,now+80*60000).chain[1].arrival,at(70),'try later transfer when first arrives too late');
assert.match(app,/async function findDirectTrips\(/,'route search is async');
assert.match(app,/await Promise\.all\(\[resolveTypedLocation\('originSearch'\),resolveTypedLocation\('place'\)\]\)/,'typed locations are resolved');
assert.match(html,/id="liveTripScreen"/,'dedicated live trip screen exists');
assert.match(html,/id="appLive"/,'live trip tab exists');
assert.match(app+'\n'+navigation,/navigator\.serviceWorker\.register\('\/sw\.js'\)/,'PWA registration exists');
const ids=[...html.matchAll(/id="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(ids).size,ids.length,'HTML IDs are unique');
assert.match(html,/href="\/assets\/app\.css"/,'external stylesheet linked');
assert.match(html,/src="\/assets\/app\.js"/,'application script linked');
assert.match(html,/src="\/assets\/navigation\.js"/,'navigation script linked');
assert.match(css,/\.welcome/,'styles extracted');
assert.match(design,/--berkeley-blue:#003262/,'Berkeley blue design token present');
assert.match(design,/--california-gold:#fdb515/,'California gold design token present');
assert.match(html,/href="\/assets\/design\.css"/,'new design stylesheet linked');
assert.match(html,/id="appRewards"/,'rewards navigation retained');
assert.match(html,/id="appLive"/,'live tracking navigation retained');
assert.match(html,/id="savedDestinations"/,'saved destinations region exists');
assert.match(html,/id="recentTrips"/,'recent searches region exists');
assert.match(html,/id="guideScreen"/,'dedicated guide screen exists');
assert.match(html,/id="guideEmpty"/,'guide empty state exists');
assert.match(html,/id="largeText"/,'large text preference exists');
assert.match(html,/id="highContrast"/,'high contrast preference exists');
assert.match(html,/id="showOnboarding"/,'onboarding control exists');
assert.match(html,/src="\/assets\/experience\.js"/,'experience controller loaded');
assert.match(app,/route-result-badge/,'route cards expose transfer badges');
assert.match(app,/nav-step-symbol/,'guide steps expose timeline icons');
assert.match(html,/src="\/assets\/guide\.js"/,'guide controller loaded');
assert.match(html,/src="\/assets\/dashboard\.js"/,'dashboard script loaded');
assert.match(dashboard,/localStorage\.setItem/,'saved places persist locally');
assert.doesNotMatch(html,/data-delay="(?:5|10|15)"/,'no manual delay reward buttons');
assert.doesNotMatch(html,/Report a 10-minute delay/,'no nonfunctional reporting');
assert.match(app,/Date\.now\(\)-journey\.sampled>150000/,'stale predictions rejected for rewards');
assert.match(app,/if\(journey\.demo\)\{/,'demo balance handled separately');
assert.match(app,/Number\.isFinite\(journey\.delay\)/,'delay must be a finite number');
console.log('Journey, rewards and UI contract tests passed');
